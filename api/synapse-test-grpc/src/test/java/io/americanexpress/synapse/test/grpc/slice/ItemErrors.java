package io.americanexpress.synapse.test.grpc.slice;

import io.americanexpress.synapse.core.error.ErrorCategory;
import io.americanexpress.synapse.core.error.ErrorDetails;

/** Error codes of the fixture service. */
enum ItemErrors implements ErrorDetails {

    ITEM_NOT_FOUND("Item {0} was not found", ErrorCategory.NOT_FOUND);

    private final String messageTemplate;

    private final ErrorCategory category;

    ItemErrors(String messageTemplate, ErrorCategory category) {
        this.messageTemplate = messageTemplate;
        this.category = category;
    }

    @Override
    public String code() {
        return name();
    }

    @Override
    public String messageTemplate() {
        return messageTemplate;
    }

    @Override
    public ErrorCategory category() {
        return category;
    }
}
