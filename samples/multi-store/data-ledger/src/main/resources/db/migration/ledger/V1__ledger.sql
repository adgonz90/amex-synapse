-- The ledger store's first migration, run by the store's own Flyway at startup, in the ledger's own database. The
-- database numbers the entries. order_id refers to an order in the orders store, another database, so it can't be a
-- foreign key. The audit columns have the entry's own names (LedgerEntry maps them) and are timestamp(6), the
-- precision Synapse truncates its stamps to.
CREATE TABLE ledger_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    entry_created TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    entry_created_by VARCHAR(255) NOT NULL,
    entry_modified TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    entry_modified_by VARCHAR(255) NOT NULL
);
CREATE INDEX ledger_entry_order_id ON ledger_entry (order_id);
